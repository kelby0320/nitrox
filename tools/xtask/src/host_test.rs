//! `test`: every workspace's host tests.

use crate::*;

pub(crate) fn cmd_test() -> R<()> {
    let tools_manifest = repo_root().join("tools").join("Cargo.toml");
    run(Command::new("cargo").arg("test").arg("--manifest-path").arg(&tools_manifest))?;

    // The kernel's `.cargo/config.toml` pins `x86_64-unknown-none`, which cannot link the test
    // harness, so the host triple is forced; `--lib` skips the `#![no_main]` bin.
    let host = host_triple()?;
    let kernel_dir = repo_root().join("kernel");
    run(Command::new("cargo").arg("test").arg("--lib").arg("--target").arg(&host).current_dir(&kernel_dir))?;

    // Userspace crates test from their workspace with the host `--target`; `--lib` skips bins.
    let userspace_dir = repo_root().join("userspace");
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("libkern")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("libheap")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("libos")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("libstream")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("init")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    // `libgpt` is held to **`sgdisk`**: it verifies what we write and we read what it wrote,
    // because a partition table is a format other people's firmware consumes. `gdisk` is a project
    // dependency; the tests panic with that message if it is missing.
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("libgpt")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    // `nxinstall`'s layout tests: the arithmetic is host-tested because its mistakes destroy a disk
    // and are invisible in a boot that succeeds, and `check-install`, the only boot that installs,
    // is not in CI.
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("nxinstall")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    // With `io`, so the session helpers' refusals made before any syscall are tested too.
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("librsproto")
        .arg("--features")
        .arg("io")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    // `libdraw` with `--features io`, so the framebuffer-acquisition arithmetic, where a
    // channel-order or stride mistake would live, is covered; the feature is off by default.
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("libdraw")
        .arg("--features")
        .arg("io")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("compositor")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("libsurface")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("libui")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("libterm")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("nxterm")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("libcrypto")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    // **Adding a crate to the workspace does not add it to this list**: a moved test that nobody
    // runs passes by not existing, as `libtime`'s did when it left `coreutils`.
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("libtime")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("service-mgr")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("profile-server")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("auth-service")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("clipboard-server")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("view-broker")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("device-mgr")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("storage-service")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("libusers")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("libinittoml")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("logging-service")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("fs-server-ext4")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("libfsserver")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("fs-server-fat")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("libfs")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("libprompt")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("libviews")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("coreutils")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("nxfiles")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("nxedit")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("nxsh")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;

    // `desktop-shell`'s library holds the layout arithmetic on the screen's size, with this gate's
    // aims pinned as literals.
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("desktop-shell")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;

    // **The size this file writes down as `GREETER` is measured by `desktop-session-mgr`'s host
    // tests**, so the gate's copy and the greeter's cannot drift without one failing first.
    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("desktop-session-mgr")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;

    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("libline")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;

    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("tty-server")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;

    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("libinput")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;

    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("libsession")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;

    run(Command::new("cargo")
        .arg("test")
        .arg("-p")
        .arg("input-server")
        .arg("--lib")
        .arg("--target")
        .arg(&host)
        .current_dir(&userspace_dir))?;
    Ok(())
}
